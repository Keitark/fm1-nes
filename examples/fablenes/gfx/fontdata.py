def glyph_bitmap(ch):
    """Return 16x16 list of 0/1 for a kana glyph ('+' counts as ink)."""
    rows = KANA[ch]
    return [[1 if c in '#+' else 0 for c in row.ljust(16)[:16]] for row in rows]


def latin_tile(ch, color=3):
    """Return 8x8 tile (values 0..3) for a latin glyph."""
    g = FONT5X7[ch]
    t = [[0] * 8 for _ in range(8)]
    for r in range(7):
        for c in range(5):
            if g[r][c] == '1':
                t[r + 1][c + 1] = color
    return t
